export function renderText(text: string, hex: string, scale = 1, letterSpacing = 1): Image {
  const glyphs = [...text.toUpperCase()].map((char) => GLYPHS[char] ?? GLYPHS["?"] ?? []);
  const width = glyphs.length * (5 + letterSpacing) - letterSpacing;
  const out = createImage(Math.max(1, width * scale), 7 * scale);

  glyphs.forEach((rows, index) => {
    const glyph = fromGrid(rows.join("\n").replaceAll("#", "X"), { X: hex });
    const scaled = scaleNearest(glyph, scale);
    blit(out, scaled, index * (5 + letterSpacing) * scale, 0);
  });

  return out;
}

function scaleNearest(image: Image, factor: number): Image {
  if (factor === 1) {
    return image;
  }
  const out = createImage(image.width * factor, image.height * factor);
  for (let y = 0; y < out.height; y += 1) {
    for (let x = 0; x < out.width; x += 1) {
      const source = (Math.floor(y / factor) * image.width + Math.floor(x / factor)) * 4;
      const target = (y * out.width + x) * 4;
      out.data[target] = image.data[source] ?? 0;
      out.data[target + 1] = image.data[source + 1] ?? 0;
      out.data[target + 2] = image.data[source + 2] ?? 0;
      out.data[target + 3] = image.data[source + 3] ?? 0;
    }
  }
  return out;
}
